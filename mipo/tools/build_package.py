#!/usr/bin/env python3
"""Build the copy-paste production package for one episode.

Reads production/character/mipo_character.json + an episode.json and writes
<episode>/generated/:
  PROMPTS.md                 all prompts in one readable document
  prompts/00_character_sheet.txt
  prompts/scene_NN_image.txt   start-frame prompt (image model + banner reference)
  prompts/scene_NN_video.txt   motion prompt (image-to-video model)
  prompts/negative.txt
  NARRATION_SCRIPT.md        timed voice script with delivery notes
  narration_lines.txt        one line per take, for the voice tool
  subtitles.srt              English captions
  shotlist.csv

Usage:  python3 tools/build_package.py production/episodes/ep01_missing_rainbow_color
Standard library only.
"""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAR = os.path.join(ROOT, "production", "character", "mipo_character.json")


def srt_time(s):
    ms = int(round(s * 1000))
    h, ms = divmod(ms, 3600000)
    m, ms = divmod(ms, 60000)
    sec, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{sec:02d},{ms:03d}"


def mmss(s):
    return f"0:{s:05.2f}"


def main(ep_dir):
    ch = json.load(open(CHAR))
    ep = json.load(open(os.path.join(ep_dir, "episode.json")))
    out = os.path.join(ep_dir, "generated")
    pdir = os.path.join(out, "prompts")
    os.makedirs(pdir, exist_ok=True)
    fmt = ep["format"]
    friends = ch["friends"]
    master = ch["authority"][0].split()[0]

    def write(name, text):
        with open(os.path.join(pdir, name), "w") as f:
            f.write(text.strip() + "\n")

    sheet = (f"Character turnaround model sheet of {ch['identity_lock']} "
             f"Five poses on a plain light background: front, three-quarter left, side, back, "
             f"three-quarter right, plus three facial expressions (happy, surprised, laughing). "
             f"Same outfit in every pose. {ch['style_lock']}")
    write("00_character_sheet.txt", sheet)
    neg_all = ch["negative"]
    write("negative.txt", neg_all)

    md = [f"# {ep['title']} - 3D prompt package (Episode {ep['episode']})", "",
          "> Generated by `tools/build_package.py` from `episode.json` + `mipo_character.json`. "
          "Edit those files, not this one.", "",
          f"**Format:** {fmt['width']}x{fmt['height']} ({fmt['aspect']}), {fmt['fps']} fps, {fmt['duration']:.0f} s  ",
          f"**Master character reference (attach to EVERY generation):** `{master}`  ",
          f"**Missing color rule:** {ep['missing_color_note']}", "",
          "## Step 0 - Character sheet (generate once per series, approve, then reuse)", "",
          "```text", sheet, "```", "",
          "## Global negative prompt", "", "```text", neg_all, "```", "",
          "## Friends (locked designs)", ""]
    md += [f"- **{k.title()}:** {v}" for k, v in friends.items()]
    md += ["", "## World", "", ch["world"], ""]

    rows = []
    for sc in ep["scenes"]:
        n = sc["id"]
        dur = sc["end"] - sc["start"]
        img = (f"Vertical 9:16 frame. {sc['start_frame']} "
               f"Character: {ch['identity_lock']} {ch['style_lock']}")
        vid = (f"{sc['motion']} {ch['identity_short']} "
               f"Keep his face, hair, outfit, backpack and wand exactly the same throughout. "
               f"Smooth cinematic camera: {sc.get('camera_motion', sc['camera'])} Gentle, kid-safe, {dur:.1f} seconds, vertical 9:16.")
        neg = neg_all + ", " + sc.get("negative_extra", "")
        write(f"scene_{n:02d}_image.txt", img)
        write(f"scene_{n:02d}_video.txt", vid)
        write(f"scene_{n:02d}_negative.txt", neg)
        md += [f"## Scene {n} - {sc['name']} ({mmss(sc['start'])}-{mmss(sc['end'])}, {dur:.1f} s)", "",
               f"**Location:** {sc['location']}  ", f"**Camera:** {sc['camera']}  "]
        if sc.get("staging"):
            md += [f"**Staging:** {sc['staging']}  "]
        md += ["", "**Beats:**", ""] + [f"- {b}" for b in sc["beats"]] + [
            "", "**A. Start-frame image prompt** (image model + banner reference):", "",
            "```text", img, "```", "",
            "**B. Image-to-video motion prompt** (use the approved start frame; add end frame if the tool supports it):", "",
            "```text", vid, "```", "",
            f"**End frame:** {sc['end_frame']}  ",
            f"**Continuity:** {sc['continuity']}  ",
            f"**Scene negative additions:** {sc.get('negative_extra', '-')}", ""]
        rows.append([n, sc["name"], sc["start"], sc["end"], dur, sc["location"], sc["camera"],
                     f"prompts/scene_{n:02d}_image.txt", f"prompts/scene_{n:02d}_video.txt",
                     f"clips/scene_{n:02d}.mp4"])
    open(os.path.join(out, "PROMPTS.md"), "w").write("\n".join(md) + "\n")

    with open(os.path.join(out, "shotlist.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scene", "name", "start", "end", "duration", "location", "camera",
                    "image_prompt", "video_prompt", "approved_clip"])
        w.writerows(rows)

    v = ep["voice"]
    nm = [f"# {ep['title']} - Narration script", "",
          f"**Voice:** {v['character']}. {v['description']}  ",
          f"**Note on line 1:** {v['line_01_note']}", "",
          "Times are positions on the final 30.0 s timeline. `Must end` is the latest the line may finish "
          "before it collides with the next beat. Record each line as its own file "
          "(`L01.wav` ... `L10.wav`), 2-3 takes each, and keep the best take.", "",
          "| ID | Start | Must end | Line | Delivery |", "|---|---|---|---|---|"]
    for ln in ep["narration"]:
        extra = f" (alt: *{ln['alt']}*)" if ln.get("alt") else ""
        sync = f" **Sync: '{ln['sync_point']['word']}' at {ln['sync_point']['time']:.2f} s.**" if ln.get("sync_point") else ""
        nm.append(f"| {ln['id']} | {ln['start']:.2f} | {ln['must_end']:.2f} | {ln['text']}{extra} | {ln['delivery']}.{sync} |")
    nm += ["", "## Plain script", ""]
    nm += [f"[{mmss(ln['start'])}] {ln['text']}" for ln in ep["narration"]]
    nm += ["", "## Sound effects cue sheet", "", "| Time | Cue |", "|---|---|"]
    nm += [f"| {c['t']:.2f} | {c['cue']} |" for c in ep["sfx"]]
    nm += ["", "## Music brief", "", ep["music"], ""]
    open(os.path.join(out, "NARRATION_SCRIPT.md"), "w").write("\n".join(nm) + "\n")
    open(os.path.join(out, "narration_lines.txt"), "w").write(
        "\n".join(f"{ln['id']}\t{ln['text']}" for ln in ep["narration"]) + "\n")
    srt = [f"{i}\n{srt_time(ln['start'])} --> {srt_time(ln['must_end'])}\n{ln['text']}\n"
           for i, ln in enumerate(ep["narration"], 1)]
    open(os.path.join(out, "subtitles.srt"), "w").write("\n".join(srt))
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else
         os.path.join(ROOT, "production", "episodes", "ep01_missing_rainbow_color"))
